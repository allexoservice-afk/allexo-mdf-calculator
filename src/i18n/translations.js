/**
 * @param {Locale} locale
 * @param {string} path dot-separated, e.g. "hero.title"
 */
export function translate(locale, path) {
  const keys = path.split('.')
  /** @param {Locale} L */
  function pick(L) {
    let o = /** @type {unknown} */ (TRANSLATIONS[L])
    for (const k of keys) {
      if (o == null || typeof o !== 'object') return undefined
      o = /** @type {Record<string, unknown>} */ (o)[k]
    }
    return typeof o === 'string' ? o : undefined
  }
  const v = pick(locale)
  if (v !== undefined) return v
  return pick(FALLBACK_LOCALE) ?? path
}

/** @param {Locale} locale @param {import('../constants/sizeCategories.js').SizeCategoryId | string} id */
export function sizeCategoryLabel(locale, id) {
  return translate(locale, `sizes.${id}`)
}

/** @param {Locale} locale @param {number} n */
export function windowsCountPhrase(locale, n) {
  if (locale === 'uk') {
    const mod10 = n % 10
    const mod100 = n % 100
    if (mod10 === 1 && mod100 !== 11) return `${n} вікно`
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return `${n} вікна`
    return `${n} вікон`
  }
  if (locale === 'fr') {
    return n === 1 ? `${n} fenêtre` : `${n} fenêtres`
  }
  if (locale === 'nl') {
    return n === 1 ? `${n} raam` : `${n} ramen`
  }
  return n === 1 ? `${n} window` : `${n} windows`
}

